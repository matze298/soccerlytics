_TEAM_COLORS_BY_NORMALIZED_NAME = {normalize_team_name(team): colors for team, colors in TEAM_COLORS.items()}


def team_marker_colors(team: str) -> tuple[str, str]:
    """Return a team's visible fill and secondary border colors.

    Returns:
        A ``(fill, border)`` pair. White primary fills use the secondary color as the fill.
    """
    primary, secondary = _TEAM_COLORS_BY_NORMALIZED_NAME.get(normalize_team_name(team), ("#3F536B", "#FFFFFF"))
    if primary.upper() in {"#FFF", "#FFFFFF"}:
        return secondary, primary
    return primary, secondary
